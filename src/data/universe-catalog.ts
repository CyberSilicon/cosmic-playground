import { Destination as BaseDestination } from './destinations';

export type UniverseRegion = 'Système solaire' | 'Voie lactée';
export type TravelExperienceType = 'surface' | 'flyby' | 'orbit' | 'speculative-view' | 'depth-probe';
export type CelestialCategory =
  | 'star' | 'terrestrial_planet' | 'gas_giant' | 'ice_giant' | 'dwarf_planet'
  | 'moon' | 'ocean_world' | 'asteroid' | 'stellar_system' | 'exoplanet';
export type ObservationTier = 'direct_imaging' | 'transit' | 'radial_velocity' | 'astrometry';

export interface ScienceTiers {
  observed: string[]; // Observations directes (mesures instrumentales réelles)
  deduced: string[];  // Déductions issues de modèles astrophysiques
  hypothetical: string[]; // Spéculations non confirmées ou hypothèses actives
}

export interface UniverseCatalogDestination {
  id: string; name: string; nameEn: string;
  category: CelestialCategory; region: UniverseRegion;
  experienceType: TravelExperienceType; phase: 'start' | 'later' | 'distant' | 'very-distant';
  texturePath: string; colorHex: string; glowColor: string; trajectoryColor: string;
  mapPosition: { xPercent: number; yPercent: number; zCamera: number };
  baseRadius: number; ringsRadius?: { inner: number; outer: number };
  discoveryYear?: number; observationYear?: number;
  tagline: string; groundExplorationConceptuallyPossible: boolean;
  asteroidsCount?: number;
  distanceToEarth: { min: string; max: string; average: string; note: string };
  scientificDataStatus: 'to_verify' | 'confirmed' | 'artist_conceptual' | 'inferred';
  surfaceStatus: 'observed' | 'modelled' | 'artist_concept';
  scienceTiers?: ScienceTiers;
  detectionMethods?: ObservationTier[];
  scientificAttribution: string; scientificNotes?: string;
  knownMaterials?: string[]; hasMagneticField?: boolean;
  habitableZone?: { min: string; max: string; note: string };
  surfaceType?: 'rocky' | 'gaseous' | 'icy' | 'unknown' | 'rocky_hot';
  hostStarTempCelsius?: number; massJupiter?: number; radiusJupiter?: number;
  orbitalSemiMajorAxisAu?: number; orbitalPeriodDays?: number;
  transitDetected?: boolean; habitabilityIndex?: number;
}

